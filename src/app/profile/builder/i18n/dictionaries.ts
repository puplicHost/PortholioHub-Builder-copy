export const builderDictionaries: Record<BuilderLocale, BuilderDictionary> = { en, ar }

const missingKeyWarnings = new Set<string>()

function lookup(locale: BuilderLocale, key: string): string | undefined {
  const value = builderDictionaries[locale][key]
  if (value !== undefined) return value
  const fallback = builderDictionaries[DEFAULT_BUILDER_LOCALE][key]
  if (fallback !== undefined) {
    if (process.env.NODE_ENV !== 'production' && !missingKeyWarnings.has(`${locale}:${key}`)) {
      missingKeyWarnings.add(`${locale}:${key}`)
      console.warn(`[builder-i18n] missing "${key}" for locale "${locale}" — falling back to "${DEFAULT_BUILDER_LOCALE}"`)
    }
    return fallback
  }
  return undefined
}

function interpolate(value: string, vars?: Record<string, string | number>): string {
  if (!vars) return value
  let out = value
  for (const [name, raw] of Object.entries(vars)) {
    out = out.replaceAll(`{${name}}`, String(raw))
  }
  return out
}

/**
 * Translate a builder chrome key for the given locale.
 * - Supports `{name}` interpolation via `vars`.
 * - Supports plurals: with `vars.count`, resolves `key.<pluralCategory>` then
 *   `key.other` (en: one/other, ar: zero/one/two/few/many/other).
 * - Falls back to English, then to the key itself (never throws).
 */
export function translate(
  locale: BuilderLocale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let resolved = key

  if (vars && typeof vars.count === 'number') {
    let category = 'other'
    try {
      category = new Intl.PluralRules(locale).select(vars.count)
    } catch {
      category = 'other'
    }
    resolved =
      lookup(locale, `${key}.${category}`) ??
      lookup(locale, `${key}.other`) ??
      lookup(locale, key) ??
      key
  } else {
    resolved = lookup(locale, key) ?? key
  }

  return interpolate(resolved, vars)
}
