export type BuilderLocale = (typeof BUILDER_LOCALES)[number]
export type BuilderDir = 'ltr' | 'rtl'

export const DEFAULT_BUILDER_LOCALE: BuilderLocale = 'en'
export const BUILDER_LOCALE_COOKIE = 'builder-locale'

export function isBuilderLocale(value: unknown): value is BuilderLocale {
  return value === 'en' || value === 'ar'
}

export function builderDir(locale: BuilderLocale): BuilderDir {
  return locale === 'ar' ? 'rtl' : 'ltr'
}

